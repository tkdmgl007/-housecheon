window.VILLA_ALIASES = (()=>{
  const cnt={}, map={};
  const add=(al,nm)=>{ if(al.length<2||al===nm) return; cnt[al]=(cnt[al]||0)+1; map[al]=nm; };
  for(const {name} of VILLA_LIST){
    const base=name.replace(/\(.*\)/,'');
    add(base,name);
    const short=base.replace(/(빌리지|빌라|하우스|빌딩|주택|캐슬|빌|홈)$/,'');
    add(short,name);
  }
  add('노블','노블레스빌'); add('트윈빌라I','트윈1'); add('트윈빌라II','트윈2');
  return Object.entries(map).filter(([al])=>cnt[al]===1).sort((x,y)=>y[0].length-x[0].length);
})();
